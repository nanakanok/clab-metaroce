#!/usr/bin/env python3
"""Generate the containerlab topology and FRR configs for a multi-plane leaf-spine.

  ./gen.py [--planes 2] [--spines 4] [--leaves 4] [--hosts-per-leaf 2]

Every plane is an independent IPv6 leaf-spine fabric (eBGP unnumbered).
Each host has one NIC per plane: ethN connects to leaf<l> of plane N.
Addressing: host i on leaf l, plane p = fd00:<p>:<l>:<i>::10/64, gateway fd00:<p>:<l>:<i>::1.
"""
import argparse
import os
import shutil

p = argparse.ArgumentParser()
p.add_argument("--planes", type=int, default=2)
p.add_argument("--spines", type=int, default=4, help="spines per plane")
p.add_argument("--leaves", type=int, default=4, help="leaves per plane")
p.add_argument("--hosts-per-leaf", type=int, default=2)
p.add_argument("--name", default="metaroce")
p.add_argument("--frr-image", default="quay.io/frrouting/frr:10.4.0")
p.add_argument("--host-image", default="metaroce-host:6c5a3a4")
p.add_argument("--mtu", type=int, default=9000)
a = p.parse_args()

root = os.path.dirname(os.path.abspath(__file__))
cfg = os.path.join(root, "configs")
shutil.rmtree(cfg, ignore_errors=True)
os.makedirs(cfg)

DAEMONS = """bgpd=yes
zebra=yes
vtysh_enable=yes
zebra_options="  -A 127.0.0.1 -s 90000000"
bgpd_options="   -A 127.0.0.1"
"""

# L4 ECMP hash (src port carries MetaRoCE entropy), forwarding on, no DAD delay.
SYSCTL = ("sysctl -qw net.ipv6.conf.all.forwarding=1 net.ipv6.fib_multipath_hash_policy=1 "
          "net.ipv6.conf.all.accept_dad=0 net.ipv6.conf.default.accept_dad=0")


def spine(pl, s):
    return f"p{pl}-spine{s}"


def leaf(pl, l):
    return f"p{pl}-leaf{l}"


def host(l, i):
    return f"h{(l - 1) * a.hosts_per_leaf + i}"


def frr_conf(name, asn, rid, ifaces, networks):
    lines = [f"frr defaults datacenter", f"hostname {name}", "log syslog informational", "!"]
    for i in ifaces:
        lines += [f"interface {i}", " ipv6 nd ra-interval 3", " no ipv6 nd suppress-ra", "!"]
    lines += [f"router bgp {asn}", f" bgp router-id {rid}", " bgp bestpath as-path multipath-relax",
              " no bgp ebgp-requires-policy", " neighbor FABRIC peer-group",
              " neighbor FABRIC remote-as external", " neighbor FABRIC timers 1 3"]
    lines += [f" neighbor {i} interface peer-group FABRIC" for i in ifaces]
    lines += [" !", " address-family ipv6 unicast", "  neighbor FABRIC activate", "  maximum-paths 64"]
    lines += [f"  network {n}" for n in networks]
    lines += [" exit-address-family", "!"]
    return "\n".join(lines) + "\n"


def write_frr(name, conf):
    d = os.path.join(cfg, name)
    os.makedirs(d)
    open(os.path.join(d, "frr.conf"), "w").write(conf)
    open(os.path.join(d, "daemons"), "w").write(DAEMONS)
    open(os.path.join(d, "vtysh.conf"), "w").write("service integrated-vtysh-config\n")


nodes, links = [], []
for pl in range(1, a.planes + 1):
    # spine s: eth<l> -> leaf l. leaf l: eth<s> -> spine s, eth<spines+i> -> host i.
    for s in range(1, a.spines + 1):
        ifs = [f"eth{l}" for l in range(1, a.leaves + 1)]
        write_frr(spine(pl, s), frr_conf(spine(pl, s), 65000 + pl, f"10.{pl}.0.{s}", ifs, []))
        nodes.append((spine(pl, s), "frr"))
    for l in range(1, a.leaves + 1):
        ifs = [f"eth{s}" for s in range(1, a.spines + 1)]
        # each host port is a routed /64 (no L2 bridge on the leaf)
        host_ifs = [f"interface eth{a.spines + i}\n ipv6 address fd00:{pl}:{l}:{i}::1/64\n!"
                    for i in range(1, a.hosts_per_leaf + 1)]
        nets = [f"fd00:{pl}:{l}:{i}::/64" for i in range(1, a.hosts_per_leaf + 1)]
        conf = frr_conf(leaf(pl, l), 65000 + pl * 100 + l, f"10.{pl}.1.{l}", ifs, nets)
        conf = conf.replace("router bgp", "\n".join(host_ifs) + "\nrouter bgp", 1)
        write_frr(leaf(pl, l), conf)
        nodes.append((leaf(pl, l), "frr"))
        for s in range(1, a.spines + 1):
            links.append((f"{spine(pl, s)}:eth{l}", f"{leaf(pl, l)}:eth{s}"))
        for i in range(1, a.hosts_per_leaf + 1):
            links.append((f"{leaf(pl, l)}:eth{a.spines + i}", f"{host(l, i)}:eth{pl}"))

hosts = [host(l, i) for l in range(1, a.leaves + 1) for i in range(1, a.hosts_per_leaf + 1)]
host_lines = {}
for l in range(1, a.leaves + 1):
    for i in range(1, a.hosts_per_leaf + 1):
        ex = []
        for pl in range(1, a.planes + 1):
            ex += [f"ip -6 addr add fd00:{pl}:{l}:{i}::10/64 dev eth{pl} nodad",
                   f"ip -6 route add fd00:{pl}::/32 via fd00:{pl}:{l}:{i}::1 dev eth{pl}"]
        host_lines[host(l, i)] = ex
for h in hosts:
    nodes.append((h, "host"))

out = [f"# generated by gen.py --planes {a.planes} --spines {a.spines} --leaves {a.leaves} "
       f"--hosts-per-leaf {a.hosts_per_leaf}", f"name: {a.name}", "", "topology:", "  defaults:",
       "    kind: linux", "  nodes:"]
for n, kind in nodes:
    if kind == "frr":
        out += [f"    {n}:", f"      image: {a.frr_image}", "      binds:",
                f"        - configs/{n}/frr.conf:/etc/frr/frr.conf",
                f"        - configs/{n}/daemons:/etc/frr/daemons",
                f"        - configs/{n}/vtysh.conf:/etc/frr/vtysh.conf",
                "      exec:", f"        - {SYSCTL}"]
    else:
        out += [f"    {n}:", f"      image: {a.host_image}", "      binds:",
                "        - scripts:/scripts:ro", "      exec:",
                "        - sysctl -qw net.ipv6.conf.all.accept_dad=0 net.ipv6.conf.default.accept_dad=0"]
        out += [f"        - {c}" for c in host_lines[n]]
out += ["  links:"]
for x, y in links:
    out += [f'    - endpoints: ["{x}", "{y}"]', f"      mtu: {a.mtu}"]
open(os.path.join(root, "metaroce.clab.yml"), "w").write("\n".join(out) + "\n")
print(f"{len(nodes)} nodes, {len(links)} links -> metaroce.clab.yml, configs/")
